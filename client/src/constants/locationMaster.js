export const getStatesForCountry = (country) => {
  const normalized = String(country || '').trim().toLowerCase();
  return LOCATION_MASTER.find((item) => item.country.toLowerCase() === normalized)?.states || [];
};

export const getCitiesForState = (country, state) => {
  const normalized = String(state || '').trim().toLowerCase();
  return getStatesForCountry(country).find((item) => item.name.toLowerCase() === normalized)?.cities || [];
};

